// Runs on every Netlify build. Combines the plain-English policy and price sheet
// into one module the bot imports, so RJ can edit the .md files directly on GitHub.
import { readFileSync, writeFileSync } from "node:fs";

const policy = readFileSync(new URL("../bot/policy.md", import.meta.url), "utf8");
const prices = readFileSync(new URL("../bot/price-sheet.md", import.meta.url), "utf8");
const prompt = `${policy}\n\n# Price sheet (the only source of facts you may quote)\n\n${prices}`;

writeFileSync(
  new URL("../netlify/lib/knowledge.mjs", import.meta.url),
  `// Generated by scripts/build-knowledge.mjs. Edit bot/policy.md or bot/price-sheet.md instead.\nexport const SYSTEM_PROMPT = ${JSON.stringify(prompt)};\n`
);
console.log(`Bot knowledge built: ${prompt.length} characters.`);
